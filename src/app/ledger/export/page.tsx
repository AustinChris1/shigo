import { redirect } from "next/navigation";
import { db } from "@/lib/db";
import { currentSeller } from "@/lib/session";
import { naira } from "@/lib/money";
import { PrintButton } from "@/components/PrintButton";

export const dynamic = "force-dynamic";

// One page the student can attach to a loan application. Print to PDF from the browser.
export default async function Export() {
  const seller = await currentSeller();
  if (!seller) redirect("/login");
  const rows = await db.ledgerEntry.findMany({ where: { sellerId: seller.id }, orderBy: { date: "asc" }, include: { order: { include: { credit: true } } } });

  const months = new Map<string, { sum: number; n: number }>();
  for (const r of rows) {
    const k = r.date.toLocaleDateString("en-NG", { month: "long", year: "numeric" });
    const c = months.get(k) ?? { sum: 0, n: 0 };
    months.set(k, { sum: c.sum + r.amountKobo, n: c.n + 1 });
  }
  const total = rows.reduce((a, r) => a + r.amountKobo, 0);
  const avg = rows.length ? Math.round(total / rows.length) : 0;
  const first = rows[0]?.date;
  const last = rows[rows.length - 1]?.date;

  return (
    <main className="space-y-6 bg-white p-2">
      <div className="no-print flex justify-between">
        <a href="/ledger" className="text-sm text-[var(--muted)]">← Ledger</a>
        <PrintButton />
      </div>

      <header className="border-b border-[var(--line)] pb-4">
        <h1 className="text-2xl font-bold">Verified income record</h1>
        <p className="text-sm text-[var(--muted)]">Generated by Shigo on {new Date().toLocaleDateString("en-NG", { day: "numeric", month: "long", year: "numeric" })}</p>
      </header>

      <section className="grid grid-cols-2 gap-4 text-sm">
        <div><div className="text-[var(--muted)]">Seller</div><div className="font-semibold">{seller.name}</div></div>
        <div><div className="text-[var(--muted)]">Phone</div><div className="font-semibold">{seller.phone}</div></div>
        <div><div className="text-[var(--muted)]">Receiving account</div><div className="font-semibold">{seller.bankName} {seller.accountNumber}</div></div>
        <div><div className="text-[var(--muted)]">Period</div><div className="font-semibold">{first ? `${first.toLocaleDateString("en-NG")} to ${last?.toLocaleDateString("en-NG")}` : "no payments yet"}</div></div>
        <div><div className="text-[var(--muted)]">Confirmed payments</div><div className="font-semibold">{rows.length}</div></div>
        <div><div className="text-[var(--muted)]">Total received</div><div className="font-semibold">{naira(total)}</div></div>
        <div><div className="text-[var(--muted)]">Average order</div><div className="font-semibold">{naira(avg)}</div></div>
        <div><div className="text-[var(--muted)]">Months with inflows</div><div className="font-semibold">{months.size}</div></div>
      </section>

      <section>
        <h2 className="mb-2 font-semibold">By month</h2>
        <table className="w-full text-sm">
          <thead><tr className="border-b border-[var(--line)] text-left text-[var(--muted)]"><th className="py-1">Month</th><th>Paid orders</th><th className="text-right">Received</th></tr></thead>
          <tbody>
            {[...months.entries()].map(([k, v]) => (
              <tr key={k} className="border-b border-[var(--line)]"><td className="py-1">{k}</td><td>{v.n}</td><td className="text-right">{naira(v.sum)}</td></tr>
            ))}
          </tbody>
        </table>
      </section>

      <section>
        <h2 className="mb-2 font-semibold">Every confirmed payment</h2>
        <table className="w-full text-xs">
          <thead><tr className="border-b border-[var(--line)] text-left text-[var(--muted)]"><th className="py-1">Date</th><th>Order</th><th>Confirmed by</th><th className="text-right">Amount</th></tr></thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r.id} className="border-b border-[var(--line)]">
                <td className="py-1">{r.date.toLocaleDateString("en-NG")}</td>
                <td>{r.order.reference}{r.order.note ? ` · ${r.order.note}` : ""}</td>
                <td>{r.order.credit?.rail ?? ""}{r.order.credit?.payerName ? ` · ${r.order.credit.payerName}` : ""}</td>
                <td className="text-right">{naira(r.amountKobo)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>

      <p className="text-xs text-[var(--muted)]">
        Each row is a credit the receiving bank notified Shigo of, matched to one order. This record is evidence the seller chooses to share.
        It is not a credit decision; a licensed lender makes that.
      </p>
    </main>
  );
}
